"""Write docs/PROGRESS.md: every routine reachable in the ROM and how far it is.

  py tools/progress.py <rom>

Status per routine:
  verified  - C version passes conformance.py (runs natively by default)
  failing   - C version exists, but conformance.py finds a difference
  untested  - C version exists, the canvas tour never runs it
  todo      - no C version yet (runs as original ROM code)
"Tour" says whether the canvas tour executes the routine, i.e. whether
conformance.py can check it at all today.

Inputs: snesrecomp's callgraph crawler (reachable functions and jump-table
targets), the func_table_register calls in src/, and the last
conformance run (scratch/conf/results.txt; run tools/conformance.py first).
"""
import os, re, sys, glob
from pathlib import Path
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, os.path.join(ROOT, "ext", "snesrecomp", "tools"))
import callgraph  # noqa: E402


def main():
    rom = sys.argv[1]
    data = Path(rom).read_bytes()
    if len(data) % 1024 == 512:
        data = data[512:]
    functions, edges, *_ = callgraph.crawl(data)

    ported = set()
    for f in glob.glob(os.path.join(ROOT, "src", "recomp", "*.c")):
        ported |= {int(a, 16) for a in re.findall(r"func_table_register\(0x([0-9A-Fa-f]{6})", open(f).read())}

    results = {}
    rp = os.path.join(ROOT, "scratch", "conf", "results.txt")
    if os.path.exists(rp):
        for line in open(rp):
            p = line.split()
            results[int(p[0], 16)] = p[1]

    # Routines checked in their own scenario runs (conformance.py --scenario,
    # the INNER sets) and enabled in the launcher: main.c's k_verified.
    mc = open(os.path.join(ROOT, "src", "main", "main.c")).read()
    kv = mc[mc.index("k_verified[] ="):]
    kv = kv[:kv.index(";")]
    for a in re.findall(r"([0-9A-F]{6})[LF]*", "".join(re.findall(r'"([^"]*)"', kv))):
        results.setdefault(int(a, 16), "PASS")
    # Frame drivers present a frame themselves: conformance.py does not check
    # them, they wait for the next frame in both versions.
    dl = mc[mc.index("k_frame_drivers[] ="):]
    drivers = {int(a, 16) for a in re.findall(r"([0-9A-F]{6})", dl[:dl.index(";")])}

    executed = set()
    ep = os.path.join(ROOT, "scratch", "conf", "executed.txt")
    if os.path.exists(ep):
        executed = {int(a, 16) for a in open(ep).read().split()}
    executed |= set(results)

    rows = []
    for f in sorted(functions | ported):
        if f in results:
            st = "verified" if results[f] == "PASS" else ("failing" if f in ported else "todo")
        elif f in drivers and f in ported:
            st = "driver"
        else:
            st = "untested" if f in ported else "todo"
        rows.append((f, st, f in executed, len(edges.get(f, ()))))

    c = Counter(r[1] for r in rows)
    total = len(rows)
    played_set = {f for f in executed}
    played = len(played_set)
    played_ok = sum(1 for f in played_set if results.get(f) == "PASS")
    played_c = sum(1 for f in played_set if f in ported)
    out = ["# Translation progress", "",
           "Generated by `tools/progress.py` from the ROM's call graph and the last",
           "`tools/conformance.py` run. Do not edit by hand.", "",
           f"**{c['verified']} of {total}** reachable routines are verified C "
           f"({100 * c['verified'] // total}%).", "",
           "| Status | Count | Meaning |", "|---|---|---|",
           f"| verified | {c['verified']} | C version matches the ROM, runs natively |",
           f"| failing | {c['failing']} | C version exists, differs from the ROM |",
           f"| untested | {c['untested']} | C version exists, the tour never runs it |",
           f"| todo | {c['todo']} | no C version yet |",
           f"| driver | {c['driver']} | frame driver: C version, not compared (it waits for the frame) |", "",
           f"Of the **{played}** routines the tour runs (call targets plus the jump-entered",
           f"handlers), **{played_ok}** are verified ({100 * played_ok // max(played, 1)}%) and "
           f"{played_c} have a C version.",
           "Most todo rows the tour never runs are not entered by any executed code:",
           "labels inside routines, code reached only through tables, or bytes the",
           "call-graph crawler decoded from data.", "",
           "Tour = the canvas tour runs it, so conformance.py can check it today.",
           "Callers = how many routines call it (higher = more reuse).", ""]
    for bank in sorted({f >> 16 for f, *_ in rows}):
        out += [f"## Bank ${bank:02X}", "", "| Routine | Status | Tour | Callers |", "|---|---|---|---|"]
        for f, st, tour, callers in rows:
            if f >> 16 == bank:
                out.append(f"| ${f >> 16:02X}:{f & 0xFFFF:04X} | {st} | {'yes' if tour else ''} | {callers} |")
        out.append("")
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    Path(os.path.join(ROOT, "docs", "PROGRESS.md")).write_text("\n".join(out))
    print(f"progress: {c['verified']}/{total} verified, {c['failing']} failing, "
          f"{c['untested']} untested, {c['driver']} drivers, {c['todo']} todo; tour-run {played_ok}/{played} -> docs/PROGRESS.md")


if __name__ == "__main__":
    main()
